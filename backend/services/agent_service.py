import io
import sys
import re
import uuid
import httpx
import pandas as pd
from pathlib import Path

# Add parent directory to path for importing existing agent
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from agents import Runner, ToolCallItem, ToolCallOutputItem
from agent import data_analyst
from tools import LOADED_DATASETS, request_datasets
from tools.viz_tools import OUTPUT_DIR as CHART_OUTPUT_DIR
from core.config import settings

# Supabase client for uploading charts
from supabase import create_client

# Tools whose results report a saved chart as a "Saved to: <path>" line
CHART_TOOL_NAMES = {
    "create_bar_chart",
    "create_line_chart",
    "create_histogram",
    "create_scatter_plot",
    "create_pie_chart",
}
SAVED_TO_PATTERN = re.compile(r"^Saved to: (.+\.png)$", re.MULTILINE)

# Conversation history sent to the model
MAX_HISTORY_MESSAGES = 10
MAX_HISTORY_CHARS = 1000


def _is_allowed_download_url(url: str) -> bool:
    """Only accept signed URLs for this project's private user-files bucket."""
    if not settings.supabase_url:
        return False
    prefix = settings.supabase_url.rstrip("/") + "/storage/v1/object/sign/user-files/"
    return url.startswith(prefix) and ".." not in url


class AgentService:
    """Service for interacting with the data analysis agent."""

    def __init__(self, user_id: str):
        """Initialize agent service for a specific user (a validated UUID string)."""
        self.user_id = user_id

        # Initialize Supabase client if configured
        self.supabase = None
        if settings.supabase_url and settings.supabase_anon_key:
            self.supabase = create_client(settings.supabase_url, settings.supabase_anon_key)

    async def chat(self, message: str, conversation_history: list[dict] = None, file_info: dict = None) -> dict:
        """
        Send a message to the agent and get a response.

        Each call gets its own dataset store, so concurrent requests (from
        different users or from one user's different conversations) never see
        each other's data.

        Args:
            message: User's message
            conversation_history: Previous messages, oldest first ({role, content})
            file_info: Dict with filename and download_url from Supabase Storage

        Returns:
            dict with response text, charts, and any data previews
        """
        with request_datasets():
            return await self._chat(message, conversation_history, file_info)

    async def _chat(self, message: str, conversation_history: list[dict] | None, file_info: dict | None) -> dict:
        # Load the selected file; stop clearly if it cannot be loaded
        if file_info:
            load_error = await self._download_and_load_file(file_info)
            if load_error:
                return {
                    "response": load_error,
                    "charts": [],
                    "chart_errors": [],
                    "datasets_loaded": [],
                    "error": True,
                }

        # Build context from history (oldest first)
        context = ""
        if conversation_history:
            lines = []
            for msg in conversation_history[-MAX_HISTORY_MESSAGES:]:
                role = "User" if msg.get("role") == "user" else "Assistant"
                content = str(msg.get("content", ""))
                if len(content) > MAX_HISTORY_CHARS:
                    content = content[:MAX_HISTORY_CHARS] + "..."
                lines.append(f"{role}: {content}")
            context = "Previous conversation (oldest first):\n" + "\n".join(lines) + "\n\n"

        # Add loaded files info to message context
        loaded_files = list(LOADED_DATASETS.keys())
        if loaded_files:
            message = f"[Available datasets: {', '.join(loaded_files)}]\n\n{message}"

        # Run the agent
        full_message = f"{context}Current request:\n{message}" if context else message

        try:
            result = await Runner.run(
                data_analyst,
                full_message,
            )

            # Extract response
            response_text = result.final_output if hasattr(result, 'final_output') else str(result)

            # Charts generated by this run only (from its own tool results)
            local_charts, chart_errors = self._collect_chart_paths(result)

            # Upload charts to Supabase and get public URLs
            chart_urls = []
            for chart_path in local_charts:
                url, upload_error = await self._upload_chart_to_supabase(chart_path)
                if url:
                    chart_urls.append(url)
                else:
                    chart_errors.append(upload_error)

            return {
                "response": response_text,
                "charts": chart_urls,
                "chart_errors": chart_errors,
                "datasets_loaded": list(LOADED_DATASETS.keys()),
            }

        except Exception as e:
            return {
                "response": f"Error processing request: {str(e)}",
                "charts": [],
                "chart_errors": [],
                "datasets_loaded": list(LOADED_DATASETS.keys()),
                "error": True,
            }

    async def _download_and_load_file(self, file_info: dict) -> str | None:
        """
        Download the selected file and load it into this request's datasets.

        The file is parsed in memory and never written to local disk, so files
        with the same original name cannot overwrite each other.

        Returns None on success, or a user-facing message explaining the failure.
        """
        # Display name only; never used as a filesystem path
        filename = Path(str(file_info.get("filename") or "data.csv")).name
        download_url = file_info.get("download_url")
        failed = f"Could not load the selected file '{filename}'."

        if not download_url:
            return f"{failed} No download link was available. Please select the file again."
        if not _is_allowed_download_url(download_url):
            print(f"Rejected download URL for {filename}")
            return f"{failed} The download link was not accepted."

        ext = Path(filename).suffix.lower()
        if ext not in (".csv", ".xlsx", ".xls"):
            return f"{failed} Unsupported file type '{ext or 'none'}'. Use CSV or Excel files."

        try:
            async with httpx.AsyncClient(timeout=30.0, follow_redirects=False) as client:
                response = await client.get(download_url)
                response.raise_for_status()
                content = response.content
        except Exception as e:
            print(f"Failed to download {filename}: {e}")
            return f"{failed} It could not be downloaded from storage. Please try again."

        if len(content) > settings.max_file_size_mb * 1024 * 1024:
            return f"{failed} It is larger than {settings.max_file_size_mb}MB."

        try:
            if ext == ".csv":
                df = pd.read_csv(io.BytesIO(content))
            else:
                df = pd.read_excel(io.BytesIO(content))
        except Exception as e:
            print(f"Failed to parse {filename}: {e}")
            return f"{failed} It could not be read as a {ext} file ({type(e).__name__}). Please check the file and upload it again."

        LOADED_DATASETS[filename] = df
        print(f"Loaded file: {filename} with {len(df)} rows")
        return None

    @staticmethod
    def _collect_chart_paths(result) -> tuple[list[Path], list[str]]:
        """
        Return (chart files created by this agent run, delivery warnings).

        Reads the run's own tool results (not the assistant's reply text or the
        output directory), so a response only ever includes its own charts.
        Function tool calls (ToolCallItem) are matched to their outputs
        (ToolCallOutputItem) by call_id to keep only chart tools. A reported
        path that is missing or outside the chart directory yields a warning.
        """
        tool_names: dict[str, str] = {}
        for item in result.new_items:
            if isinstance(item, ToolCallItem):
                raw = item.raw_item
                if isinstance(raw, dict):
                    call_id, name = raw.get("call_id"), raw.get("name")
                else:
                    call_id, name = getattr(raw, "call_id", None), getattr(raw, "name", None)
                if call_id and name:
                    tool_names[call_id] = name

        output_dir = CHART_OUTPUT_DIR.resolve()
        paths: list[Path] = []
        warnings: list[str] = []
        for item in result.new_items:
            if not isinstance(item, ToolCallOutputItem):
                continue
            if tool_names.get(item.call_id) not in CHART_TOOL_NAMES:
                continue
            if not isinstance(item.output, str):
                continue
            for match in SAVED_TO_PATTERN.finditer(item.output):
                path = Path(match.group(1)).resolve()
                if path.parent != output_dir:
                    print(f"Chart path outside chart directory ignored: {path}")
                    warnings.append("A chart was reported as created, but its file location was invalid.")
                elif not path.is_file():
                    print(f"Chart file reported but missing: {path}")
                    warnings.append("A chart was reported as created, but its image file was missing.")
                elif path not in paths:
                    paths.append(path)
        return paths, warnings

    async def _upload_chart_to_supabase(self, chart_path: Path) -> tuple[str | None, str | None]:
        """
        Upload a chart to Supabase Storage.

        Returns (public_url, None) on success or (None, user-facing reason) on failure.
        Never returns a local or relative URL, since the frontend cannot load those.
        """
        if not self.supabase:
            print(f"Chart not delivered ({chart_path.name}): Supabase storage is not configured")
            return None, "A chart was created but chart storage is not configured on the server."

        try:
            # Generate unique storage path
            chart_id = str(uuid.uuid4())
            filename = f"{self.user_id}/{chart_id}.png"

            file_content = chart_path.read_bytes()

            # Upload to Supabase Storage (charts bucket is public)
            self.supabase.storage.from_("charts").upload(
                filename,
                file_content,
                {"content-type": "image/png"}
            )

            # Get public URL
            public_url = self.supabase.storage.from_("charts").get_public_url(filename)

            return public_url, None

        except Exception as e:
            print(f"Failed to upload chart {chart_path.name}: {e}")
            return None, "A chart was created but could not be uploaded."
